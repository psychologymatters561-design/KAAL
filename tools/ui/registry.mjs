/* /registry in a real browser: the twenty, a sold piece's panel, ?n=, 360px. */
import * as R from "../../worker/registry.js";
import { world, open, SITE } from "./harness.mjs";

let failed = 0;
const ok = (c, m) => { console.log((c ? "PASS " : "FAIL ") + m); if (!c) failed++; };
const W = world();
const r7 = await R.recordPayment(W.env, { series: "S01", n: 7, paymentId: "pay_UIREG0007", orderId: "order_UIREG0007", amount: 599900, email: "asha@example.com", phone: "9876543210", name: "Asha Rao", address: { city: "Pune", state: "Maharashtra" }, paidAt: new Date().toISOString() });
W.DB.raw.prepare("UPDATE orders SET status='registered', delivered_on='2026-10-23', registered_at=? WHERE id=?").run(new Date().toISOString(), r7.order.id);
W.DB.raw.prepare("UPDATE pieces SET status='registered' WHERE id='S01-07'").run();
W.DB.raw.prepare("INSERT INTO owners (email, name, phone, city, state, show_city_publicly) VALUES ('asha@example.com','Asha Rao','919876543210','Pune','Maharashtra',0)").run();
W.DB.raw.prepare("INSERT INTO ownerships (series, piece_id, owner_id, owner_no, from_at, acquired_via) VALUES ('S01','S01-07',1,1,'2026-10-23T00:00:00Z','purchase')").run();
await R.recordPayment(W.env, { series: "S01", n: 8, paymentId: "pay_UIREG0008", orderId: "order_UIREG0008", amount: 599900, email: "ravi@example.com", name: "Ravi", paidAt: new Date().toISOString() });
W.DB.raw.prepare("UPDATE pieces SET status='held', held_by='x', held_until=? WHERE id='S01-10'").run(Date.now() + 600000);
W.DB.raw.prepare("UPDATE pieces SET status='reported_stolen' WHERE id='S01-15'").run();
W.DB.raw.prepare("INSERT INTO service_log (series, piece_id, date, work_done, public_line) VALUES ('S01','S01-07','2027-03-01','x','Movement replaced under warranty')").run();

const B = await open(W, { viewport: { width: 360, height: 800 } });
const page = await B.page();
await page.goto(SITE + "/registry");
await page.waitForSelector("#grid li");
ok(await page.locator("#grid li").count() === 20, "registry: twenty cells");
ok(/Owner I/i.test(await page.locator("#grid li").nth(6).innerText()), "registry: No. 07 reads Owner I");
ok(/Being\s+claimed/i.test(await page.locator("#grid li").nth(9).innerText()), "registry: a held number says Being claimed");
ok(/Stolen/i.test(await page.locator("#grid li").nth(14).innerText()), "registry: a stolen piece is flagged");
ok(await page.locator("#retired").isHidden(), "registry: not retired while numbers remain");
const sw = await page.evaluate(() => [document.documentElement.scrollWidth, window.innerWidth]);
ok(sw[0] <= sw[1], "registry: no sideways scroll at 360px");
await page.locator("#grid li").nth(6).locator("button").click();
const panel = await page.locator("#panel").innerText();
ok(/Owner I · since [A-Z][a-z]{2} 2026/.test(panel) && /Owner’s city withheld/.test(panel) && /Movement replaced under warranty/.test(panel), "registry: the panel says Owner I since the month, the city withheld, and the public service line");
ok(!/Asha|Pune|asha@|9876/.test(panel), "registry: nothing that identifies the owner");
await page.screenshot({ path: "/tmp/registry-360.png", fullPage: true });
const p2 = await B.page();
await p2.goto(SITE + "/registry?n=15");
await p2.waitForSelector("#panel:not([hidden])");
ok(/reported stolen/i.test(await p2.locator("#panel").innerText()), "registry: ?n= opens that piece (the letter's QR code)");
const p3 = await B.page();
await p3.goto(SITE + "/registry?n=03");
await p3.waitForSelector("#panel:not([hidden])");
ok(/Available/.test(await p3.locator("#panel").innerText()) && await p3.locator("#panel a.btn").count() === 1, "registry: an available number leads to the shop");
ok(B.log.errors.length === 0 && B.log.console.length === 0, "registry: no errors " + JSON.stringify(B.log.errors.concat(B.log.console)).slice(0, 200));
await B.browser.close();
const B2 = await open(W, { viewport: { width: 1280, height: 900 } });
const d = await B2.page();
await d.goto(SITE + "/registry?n=07");
await d.waitForSelector("#panel:not([hidden])");
await d.screenshot({ path: "/tmp/registry-desktop.png", fullPage: true });
await B2.browser.close();
console.log(failed ? `\n${failed} failed.` : "\nAll registry browser checks passed.");
process.exit(failed ? 1 : 0);
